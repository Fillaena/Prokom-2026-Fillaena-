# program ini menunjukkan cara lstrip(), rstrip(), dan strip() memghapus whitespace dari sebuah nama

name = "\t\n  Fillaena \n\t"

print("Original:")
print(name)

# lstrip() menghapus whitespace di sisi kiri
print("lstrip():")
print(name.lstrip())

# rstrip() menghapus whitespace di sisi kanan
print("rstrip():")
print(name.rstrip())

# strip() menghapus whitespace di sisi kanan dan kiri
print("strip():")
print(name.strip())

